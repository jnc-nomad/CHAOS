"""
Shared thrust-curve export: one (time, thrust) history -> one RASP .eng motor file.

Both the simulation (SimulationResults.generate_thrustcurve) and the data analysis
(DataAnalysis.build_thrustcurve) call this, so a designed motor and a fired one export
identically -- the impulse-class designation, the even-grid resample, the half-second tail,
and the header layout all live here, in one place.

Inputs: time [s from ignition], thrust [N]. Motor specs: propellant_mass [kg],
length [mm], diameter [mm] -- the RASP header's native units.
"""

# Dependency imports
from datetime import datetime
import getpass
import numpy as np

# Package imports
# (none)

# RASP impulse classes: total impulse [N s] above which a motor earns each letter.
IMPULSE_THRESHOLDS = {"I": 320.01, "J": 640.01, "K": 1280.01, "L": 2560.01, "M": 5120.01,
                      "N": 10240.01, "O": 20480.01, "P": 40960.01, "Q": 81920.01,
                      "R": 163840.01, "S": 327680.01}


def generate_thrustcurve(time, thrust, propellant_mass: float, length: float,
                         diameter: float = 98, manufacturer: str = "BYUPropulsion",
                         datapoints: int = None, path: str = None,
                         source: str = None) -> dict:
    """Write a (time, thrust) history as a RASP .eng file for OpenRocket / RockSim.

    Exported as a plugged motor (no ejection charge), with the loaded propellant in both the
    propellant and total mass fields -- hardware mass belongs in the rocket design.

    Args:
        time: time samples [s], measured from ignition.
        thrust: thrust samples [N] on the same base.
        propellant_mass: loaded propellant [kg].
        length: motor length [mm] (dictated by the caller, like `diameter`).
        diameter: motor diameter [mm].
        manufacturer: used in the default output filename.
        datapoints: samples in the exported curve; defaults to 4 per second of burn.
        path: output file; defaults to "<manufacturer> <designation>.eng".
        source: optional note (e.g. a data file path) added to the header comment.

    Returns:
        dict with path, designation, total_impulse [N s], burn_time [s], average_thrust [N].
    """
    time = np.asarray(time, dtype=float)
    thrust = np.asarray(thrust, dtype=float)
    if time.size < 2:
        raise ValueError("No burn history to export (need at least two samples)")

    t0 = time[0]
    burn_time = float(time[-1] - t0)
    total_impulse = float(np.trapezoid(thrust, time))
    average_thrust = total_impulse / burn_time if burn_time > 0 else 0.0

    impulse_class = None
    for letter, threshold in IMPULSE_THRESHOLDS.items():
        if total_impulse > threshold:
            impulse_class = letter
    if impulse_class is None:
        raise ValueError(f"Total impulse {total_impulse:.1f} N-s is below I class")
    designation = f"{impulse_class}{round(average_thrust)}"

    # Resample onto an even grid. RASP implies zero thrust at t=0, so the first point is one
    # interval in; close with a half-second tail (half the final thrust, then zero).
    if datapoints is None:
        datapoints = round(burn_time * 4)
    datapoints = max(int(datapoints), 2)
    times = np.linspace(0.0, burn_time, datapoints + 1)[1:]
    thrusts = np.interp(times, time - t0, thrust)
    times = np.append(times, [burn_time + 0.25, burn_time + 0.5])
    thrusts = np.append(thrusts, [thrusts[-1] / 2, 0.0])

    # name, diameter [mm], length [mm], delays (P = plugged), propellant [kg], total [kg], mfr
    header = (f"{designation} {round(diameter)} {round(length)} P "
              f"{propellant_mass:.4f} {propellant_mass:.4f} BYU")

    if path is None:
        path = f"{manufacturer} {designation}.eng"
    with open(path, "w") as f:
        note = f" from {source}" if source else ""
        f.write(f"; Thrust curve generated by {getpass.getuser()} using CHAOS{note}. "
                f"Generated at {datetime.now():%Y-%m-%d %H:%M:%S}\n")
        f.write(f"; Total impulse {total_impulse:.1f} N-s, burn time {burn_time:.3f} s, "
                f"propellant mass only\n")
        f.write(header + "\n")
        for t_s, force in zip(times, thrusts):
            f.write(f"   {t_s:.3f} {force:.2f}\n")
        f.write(";\n")

    return {"path": path, "designation": designation, "total_impulse": total_impulse,
            "burn_time": burn_time, "average_thrust": average_thrust}
